import hashlib
from pathlib import Path

import pytest
from docx import Document

from ppm import db
from ppm.analyst.documents import create_from_template
from ppm.auth import ensure_seed_users

pytestmark = pytest.mark.db


def _template(tmp_path: Path) -> Path:
    path = tmp_path / "template.docx"
    document = Document()
    document.add_heading("Project: <Project Name>", level=1)
    document.add_paragraph("Date: <Date>")
    document.add_paragraph("Stage: <Stage>")
    document.save(path)
    return path


def _register_template(path: Path, code: str = "T001") -> None:
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    document = db.fetch_one(
        "INSERT INTO document (hash, source_path, canonical_path, source_collection, mime, "
        "ingest_status) VALUES (%s, %s, %s, 'test', 'application/vnd.openxmlformats-"
        "officedocument.wordprocessingml.document', 'indexed') RETURNING document_id",
        (digest, str(path), str(path)),
    )
    db.execute(
        "INSERT INTO template (document_id, source_collection, code, title, stage, category, "
        "format, is_blank) VALUES (%s, 'test', %s, 'Test Template', 'preparation', 'pep', 'docx', true)",
        (document["document_id"], code),
    )


def test_create_draft_from_docx_template(clean_db, tmp_path):
    ensure_seed_users()
    senior = db.fetch_one("SELECT * FROM app_user WHERE username = 'senior'")
    user = {
        "user_id": str(senior["user_id"]), "display_name": "Senior Manager",
        "role": "senior_manager", "access_level": "all",
    }
    path = _template(tmp_path)
    _register_template(path)

    result = create_from_template(
        "Test Template", user=user, fields={"project_name": "Marina Bay", "stage": "Design"}
    )
    assert result["status"] == "draft"
    assert Path(result["path"]).is_file()
    text = "\n".join(p.text for p in Document(result["path"]).paragraphs)
    assert "Marina Bay" in text
    assert "Design" in text
    assert "DRAFT generated by PPM" in text

    generated = db.fetch_one(
        "SELECT status, title FROM generated_document WHERE generated_id = %s",
        (result["generated_id"],),
    )
    assert generated["status"] == "draft"


def test_auto_pick_chooses_fillable_template(clean_db, tmp_path):
    ensure_seed_users()
    senior = db.fetch_one("SELECT * FROM app_user WHERE username = 'senior'")
    user = {
        "user_id": str(senior["user_id"]), "display_name": "Senior Manager",
        "role": "senior_manager", "access_level": "all",
    }
    first = _template(tmp_path)
    _register_template(first, code="T001")

    second = tmp_path / "template2.docx"
    document = Document()
    document.add_heading("Project: <Project Name>", level=1)
    document.add_paragraph("Second template")
    document.save(second)
    _register_template(second, code="T002")

    result = create_from_template(
        "Test Template", user=user, fields={"project_name": "Auto Pick"},
        auto_pick=True,
    )
    assert result["status"] == "draft"
    assert result["auto_picked"] is True
    assert Path(result["path"]).is_file()


def test_junior_cannot_use_restricted_project(clean_db, tmp_path):
    ensure_seed_users()
    junior = db.fetch_one("SELECT * FROM app_user WHERE username = 'junior'")
    user = {
        "user_id": str(junior["user_id"]), "display_name": "Junior Analyst",
        "role": "junior", "access_level": "baseline",
    }
    path = _template(tmp_path)
    _register_template(path)
    db.execute(
        "INSERT INTO project (name, data_class) VALUES ('Restricted Project', 'restricted')"
    )
    with pytest.raises(PermissionError):
        create_from_template(
            "Test Template", user=user, project_name="Restricted Project",
            fields={"project_name": "Restricted Project"},
        )
