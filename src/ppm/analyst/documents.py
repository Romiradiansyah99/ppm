"""Create a draft document from an office template.

Only `.docx` and `.xlsx` are supported. The result is always a draft; PPM never
sends a client-facing document. Placeholder coverage is intentionally explicit:
the returned `unfilled` list shows what a human still has to complete.
"""

from __future__ import annotations

import json
import re
from datetime import date
from pathlib import Path
from typing import Any

import openpyxl
from docx import Document

from ppm import db
from ppm.workflows.retrieval import TemplateQuery, find_templates
from ppm.config import REPO_ROOT

SUPPORTED_FORMATS = {"docx", "xlsx"}
PLACEHOLDER_RE = re.compile(r"<[^<>]{2,60}>|\[[^\[\]]{2,60}\]")


def _slug(text: str, limit: int = 70) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9]+", "-", text).strip("-").lower()
    return (cleaned or "document")[:limit]


def _replace(text: str, mapping: dict[str, str]) -> str:
    result = text
    for key, value in mapping.items():
        result = result.replace(key, value)
    return result


def _replace_paragraph(paragraph, mapping: dict[str, str]) -> None:
    original = paragraph.text
    replaced = _replace(original, mapping)
    if replaced == original:
        return
    if paragraph.runs:
        paragraph.runs[0].text = replaced
        for run in paragraph.runs[1:]:
            run.text = ""
    else:
        paragraph.add_run(replaced)


def _docx_text(document) -> str:
    parts = [paragraph.text for paragraph in document.paragraphs]
    for table in document.tables:
        for row in table.rows:
            for cell in row.cells:
                parts.extend(paragraph.text for paragraph in cell.paragraphs)
    return "\n".join(parts)


def _fill_docx(source: Path, target: Path, mapping: dict[str, str], note: str) -> list[str]:
    document = Document(str(source))
    for paragraph in document.paragraphs:
        _replace_paragraph(paragraph, mapping)
    for table in document.tables:
        for row in table.rows:
            for cell in row.cells:
                for paragraph in cell.paragraphs:
                    _replace_paragraph(paragraph, mapping)
    for section in document.sections:
        for container in (section.header, section.footer):
            for paragraph in container.paragraphs:
                _replace_paragraph(paragraph, mapping)

    if document.paragraphs:
        draft = document.paragraphs[0].insert_paragraph_before(note)
        draft.style = document.styles["Normal"]
    else:
        document.add_paragraph(note)

    document.save(str(target))
    text = _docx_text(document)
    return sorted(set(PLACEHOLDER_RE.findall(text)))[:12]


def _fill_xlsx(source: Path, target: Path, mapping: dict[str, str], note: str) -> list[str]:
    workbook = openpyxl.load_workbook(source)
    for sheet in workbook.worksheets:
        for row in sheet.iter_rows():
            for cell in row:
                if isinstance(cell.value, str):
                    cell.value = _replace(cell.value, mapping)
    meta = workbook.create_sheet("PPM")
    meta["A1"] = note
    meta["A2"] = "Status"
    meta["B2"] = "draft"
    meta["A3"] = "Generated by"
    meta["B3"] = "PPM"
    workbook.save(str(target))

    texts: list[str] = []
    for sheet in workbook.worksheets:
        for row in sheet.iter_rows(values_only=True):
            texts.extend(str(value) for value in row if isinstance(value, str))
    return sorted(set(PLACEHOLDER_RE.findall("\n".join(texts))))[:12]


def _project(project_name: str | None, user: dict) -> dict | None:
    if not project_name:
        return None
    project = db.fetch_one(
        "SELECT * FROM project WHERE name ILIKE %s LIMIT 1", (f"%{project_name}%",)
    )
    if not project:
        return None
    if user["role"] != "senior_manager" and project.get("data_class") == "restricted":
        raise PermissionError(
            f"project '{project['name']}' is restricted; your role cannot use it"
        )
    return project


def create_from_template(
    template_query: str,
    *,
    user: dict,
    project_name: str | None = None,
    fields: dict[str, str] | None = None,
    auto_pick: bool = False,
    conversation_id: str | None = None,
) -> dict[str, Any]:
    candidates = find_templates(TemplateQuery(text=template_query, limit=5), log=False)
    if not candidates:
        candidates = db.fetch_all(
            "SELECT t.*, d.source_path FROM template t "
            "LEFT JOIN document d ON d.document_id = t.document_id "
            "WHERE t.code = %s OR t.title ILIKE %s LIMIT 5",
            (template_query, f"%{template_query}%"),
        )
    if not candidates:
        return {"status": "not_found", "query": template_query}
    if len(candidates) > 1 and not auto_pick:
        return {
            "status": "ambiguous",
            "candidates": [
                {
                    "code": row.get("code"),
                    "title": row.get("title"),
                    "format": row.get("format"),
                    "stage": row.get("stage"),
                }
                for row in candidates[:5]
            ],
        }

    if auto_pick:
        template = next(
            (
                row for row in candidates
                if Path(row.get("source_path") or "").suffix.lower().lstrip(".") in SUPPORTED_FORMATS
            ),
            None,
        )
        if template is None:
            return {
                "status": "unsupported_format",
                "message": "No fillable .docx/.xlsx template among the candidates.",
            }
    else:
        template = candidates[0]
    if user["role"] != "senior_manager" and template.get("document_id"):
        source_doc = db.fetch_one(
            "SELECT confidentiality_class FROM document WHERE document_id = %s",
            (template["document_id"],),
        )
        if source_doc and source_doc["confidentiality_class"] != "internal":
            return {
                "status": "forbidden",
                "message": "template source is client-identifiable; senior access required",
            }

    source_path = template.get("source_path")
    if not source_path or not Path(source_path).is_file():
        return {"status": "no_source", "title": template.get("title")}

    source = Path(source_path)
    file_format = source.suffix.lower().lstrip(".")
    if file_format not in SUPPORTED_FORMATS:
        return {
            "status": "unsupported_format",
            "format": file_format,
            "message": "Only .docx and .xlsx can be filled. Convert legacy .doc first.",
        }

    project = _project(project_name, user)
    fields = dict(fields or {})
    today = date.today().isoformat()
    project_name_value = project_name or fields.get("project_name") or "Draft Project"
    client_value = fields.get("client_name") or (project or {}).get("client_label") or "[CLIENT]"
    mapping = {
        "<Project Name>": project_name_value,
        "[insert project name]": project_name_value,
        "<Client Name>": client_value,
        "[insert client name]": client_value,
        "<Date>": fields.get("date", today),
        "[Date]": fields.get("date", today),
        "<Project No.>": fields.get("project_no", ""),
        "<Stage>": fields.get("stage", (project or {}).get("stage") or ""),
        "<Cost Plan No.>": fields.get("cost_plan_no", ""),
    }
    for key, value in fields.items():
        mapping[f"<{key}>"] = str(value)
        mapping[f"[{key}]"] = str(value)
        mapping[f"{{{key}}}"] = str(value)

    output_dir = REPO_ROOT / "exports" / "documents" / user["user_id"]
    output_dir.mkdir(parents=True, exist_ok=True)
    stamp = date.today().strftime("%Y%m%d")
    title = f"{template.get('title') or source.stem} - {project_name_value}"
    target = output_dir / f"{stamp}-{_slug(title)}.{file_format}"

    note = (
        f"DRAFT generated by PPM for {user['display_name']} on {today}. "
        "Requires review before client use."
    )
    try:
        if file_format == "docx":
            unfilled = _fill_docx(source, target, mapping, note)
        else:
            unfilled = _fill_xlsx(source, target, mapping, note)
    except Exception as exc:
        return {"status": "failed", "error": str(exc)}

    generated = db.fetch_one(
        "INSERT INTO generated_document "
        "(user_id, template_id, project_id, title, path, status, fields, conversation_id) "
        "VALUES (%s, %s, %s, %s, %s, 'draft', %s, %s) RETURNING generated_id",
        (
            user["user_id"],
            template.get("template_id"),
            (project or {}).get("project_id"),
            title,
            str(target),
            json.dumps(fields),
            conversation_id,
        ),
    )
    return {
        "status": "draft",
        "generated_id": str(generated["generated_id"]),
        "title": title,
        "path": str(target),
        "template_code": template.get("code"),
        "template_title": template.get("title"),
        "unfilled": unfilled,
        "auto_picked": bool(auto_pick and len(candidates) > 1),
    }


def get_generated_document(user_id: str, generated_id: str) -> dict[str, Any] | None:
    return db.fetch_one(
        "SELECT * FROM generated_document WHERE generated_id = %s AND user_id = %s",
        (generated_id, user_id),
    )


def generated_document_bytes(user_id: str, generated_id: str) -> tuple[bytes, str, str] | None:
    row = get_generated_document(user_id, generated_id)
    if not row:
        return None
    path = Path(str(row.get("path") or ""))
    if not path.is_file():
        return None
    suffix = path.suffix.lower()
    mime = (
        "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
        if suffix == ".docx"
        else "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
    )
    return path.read_bytes(), path.name, mime
